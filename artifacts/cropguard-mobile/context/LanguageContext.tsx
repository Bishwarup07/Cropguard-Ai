interface LanguageState {
  language: LanguageCode;
  languageName: string;
  setLanguage: (language: LanguageCode) => void;
  t: (key: string, params?: TranslationParams) => string;
  translateValue: (value: string) => string;
}

const LanguageContext = createContext<LanguageState | null>(null);
const LANGUAGE_KEY = '@cropguard/language';

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>('en');

  useEffect(() => {
    AsyncStorage.getItem(LANGUAGE_KEY)
      .then((saved) => {
        if (saved === 'en' || saved === 'hi' || saved === 'bn') setLanguageState(saved);
      })
      .catch(() => undefined);
  }, []);

  const setLanguage = (nextLanguage: LanguageCode) => {
    setLanguageState(nextLanguage);
    AsyncStorage.setItem(LANGUAGE_KEY, nextLanguage).catch(() => undefined);
  };

  const value = useMemo<LanguageState>(() => {
    const t = (key: string, params: TranslationParams = {}) => {
      let text = translations[language][key] ?? translations.en[key] ?? key;
      Object.entries(params).forEach(([param, replacement]) => {
        text = text.replace(`{${param}}`, String(replacement));
      });
      return text;
    };
    return {
      language,
      languageName: languages.find((item) => item.code === language)?.nativeLabel ?? 'English',
      setLanguage,
      t,
      translateValue: (value: string) => {
        const key = dynamicKeyMap[value];
        return key ? t(key) : value;
      },
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}